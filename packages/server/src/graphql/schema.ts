function registeredEnum(standIns: Map<string, GraphQLNamedType>, name: string): GraphQLEnumType {
  const found = standIns.get(name);
  if (!(found instanceof GraphQLEnumType)) throw new Error("the schema has no enum " + name);
  return found;
}

