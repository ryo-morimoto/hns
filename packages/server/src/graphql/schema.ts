import {
  printSchema,
  GraphQLID,
  GraphQLInt,
  GraphQLList,
  GraphQLNonNull,
  GraphQLObjectType,
  GraphQLSchema,
  GraphQLString,
  GraphQLUnionType,
} from "graphql";
import { buildSchema, type MutationRootFactory } from "@hns/core/graphql";
import type { GraphQLContext } from "./context.ts";
import { failureType, allGraphqlCodes } from "./failure-type.ts";
import { buildMutationRoot, MUTATION_MODULES, type MutationModule } from "./mutations/index.ts";
import {
  resolveConversations,
  resolveIndexState,
  resolveProjects,
  resolveTasks,
} from "./resolvers.ts";

/** The first line of the generated SDL; the codegen verifier reads it. */
export const SDL_HEADER = "# Generated by @hns/server (buildSchemaSdl). Do not edit by hand.";
/** The second line of the generated SDL: the command that writes it again. */
export const SDL_COMMAND = "# Regenerate with npm run codegen.";

/** The Query vocabulary, in the published order. */
const QUERY_FAILURE_CODES = ["invalid_request", "limit_exceeded", "unavailable"] as const;

/** The failure member every result union carries. */
const QueryFailureType = failureType("QueryFailure", allGraphqlCodes(QUERY_FAILURE_CODES));

/**
 * A model object type by GraphQL name.
 *
 * @internal
 * @throws Error when the model does not register the type, which means the SDL and the server
 * disagree.
 */
function objectType(
  objects: ReadonlyMap<string, GraphQLObjectType>,
  name: string,
): GraphQLObjectType {
  const type = objects.get(name);
  if (type === undefined) throw new Error("the model has no GraphQL type " + name);
  return type;
}

/** A payload type that wraps one list field. */
function listPayload(name: string, field: string, element: GraphQLObjectType): GraphQLObjectType {
  return new GraphQLObjectType({
    name,
    fields: {
      [field]: { type: new GraphQLNonNull(new GraphQLList(new GraphQLNonNull(element))) },
    },
  });
}

/**
 * A result union: the payload or a typed failure.
 *
 * @internal
 * @remarks
 * The resolved value says which member it is by its `__typename`, so a failure can never be
 * mistaken for an empty list and no runtime class check is needed.
 */
function resultUnion(name: string, payload: GraphQLObjectType): GraphQLUnionType {
  return new GraphQLUnionType({
    name,
    types: [payload, QueryFailureType],
    resolveType: (value: { readonly __typename: string }): string => value.__typename,
  });
}

/**
 * Build the Query root over the model's own object types.
 *
 * @param objects - The model object types the schema is built with.
 * @returns The Query root; each field names its source in {@link resolveProjects},
 * {@link resolveTasks}, or {@link resolveConversations}.
 *
 * @remarks
 * The root references the instances it is given, so the schema holds one `Project` type rather
 * than a second definition with the same name.
 */
function buildQuery(objects: ReadonlyMap<string, GraphQLObjectType>): GraphQLObjectType {
  const projectList = listPayload("ProjectList", "projects", objectType(objects, "Project"));
  // The conversation payload carries the keyset cursor, so it is built here rather than by
  // listPayload: the list is a page, and the client needs the position to ask for the next one.
  const conversationList = new GraphQLObjectType({
    name: "ConversationList",
    fields: {
      conversations: {
        type: new GraphQLNonNull(
          new GraphQLList(new GraphQLNonNull(objectType(objects, "Conversation"))),
        ),
      },
      nextCursor: { type: GraphQLString },
    },
  });
  const taskList = listPayload("TaskList", "tasks", objectType(objects, "Task"));
  const indexState = new GraphQLObjectType({
    name: "IndexState",
    fields: {
      pending: { type: new GraphQLNonNull(GraphQLInt) },
      lastSyncedAt: { type: GraphQLString },
      lastErrorCode: { type: GraphQLString },
      lastErrorAt: { type: GraphQLString },
    },
  });

  return new GraphQLObjectType<undefined, GraphQLContext>({
    name: "Query",
    fields: {
      projects: {
        type: new GraphQLNonNull(resultUnion("ProjectListResult", projectList)),
        args: { first: { type: GraphQLInt } },
        resolve: resolveProjects,
      },
      conversations: {
        type: new GraphQLNonNull(resultUnion("ConversationListResult", conversationList)),
        args: {
          projectId: { type: new GraphQLNonNull(GraphQLID) },
          first: { type: GraphQLInt },
          after: { type: GraphQLString },
          q: { type: GraphQLString },
        },
        resolve: resolveConversations,
      },
      indexState: {
        type: new GraphQLNonNull(resultUnion("IndexStateResult", indexState)),
        args: { projectId: { type: new GraphQLNonNull(GraphQLID) } },
        resolve: resolveIndexState,
      },
      tasks: {
        type: new GraphQLNonNull(resultUnion("TaskListResult", taskList)),
        args: {
          projectId: { type: new GraphQLNonNull(GraphQLID) },
          first: { type: GraphQLInt },
        },
        resolve: resolveTasks,
      },
    },
  });
}

/**
 * The Mutation root builder, or undefined when no feature has registered a module.
 *
 * @internal
 * @remarks
 * The absence is what keeps the schema free of an empty Mutation root: GraphQL refuses a
 * Mutation type with no fields, and the published SDL must not change until a write exists.
 */
function mutationOf(modules: readonly MutationModule[]): MutationRootFactory | undefined {
  if (modules.length === 0) return undefined;
  return (objects) => buildMutationRoot(objects, modules);
}

/**
 * Build the schema the Worker serves.
 *
 * @param modules - The feature mutation modules to collect; production uses
 * {@link MUTATION_MODULES}. An empty collection leaves the schema without a Mutation root.
 * @returns The model types, the result unions, and the Query root (and the Mutation root when a
 * module is registered), ready for `validate` and `execute`.
 */
export function buildGraphQLSchema(
  modules: readonly MutationModule[] = MUTATION_MODULES,
): GraphQLSchema {
  return buildSchema(buildQuery, mutationOf(modules));
}

/**
 * The schema as SDL, for the client code generator.
 *
 * @param modules - The feature mutation modules to collect; production uses
 * {@link MUTATION_MODULES}.
 * @returns The printed schema, preceded by a generated header and ending in a newline.
 *
 * @remarks
 * The web package commits this as `schema.graphql`; relay-compiler validates the app's documents
 * against it. Regenerate with `npm run codegen` instead of editing it.
 */
export function buildSchemaSdl(modules: readonly MutationModule[] = MUTATION_MODULES): string {
  return SDL_HEADER + "\n" + SDL_COMMAND + "\n" + printSchema(buildGraphQLSchema(modules)) + "\n";
}
