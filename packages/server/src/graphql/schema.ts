/** The first line of the generated SDL; the codegen verifier reads it. */
export const SDL_HEADER = "# Generated by @hns/server (buildSchemaSdl). Do not edit by hand.";
/** The second line of the generated SDL: the command that writes it again. */
export const SDL_COMMAND = "# Regenerate with npm run codegen.";

/**
 * The Query vocabulary, in the published order.
 *
 * @remarks
 * `not_found` is here for the one read that addresses a single row by id (`trail(id)`): a missing
 * Trail is an answer a screen acts on, not a broken request, and the alternative — an empty
 * payload — would show as "loading" forever. `forbidden` and `conflict` are not: a Query reads
 * what the session may already read.
 */
const QUERY_FAILURE_CODES = [
  "invalid_request",
  "limit_exceeded",
  "not_found",
  "unavailable",
] as const;

/** The failure member every result union carries. */
const QueryFailureType = failureType("QueryFailure", allGraphqlCodes(QUERY_FAILURE_CODES));

/**
 * A model object type by GraphQL name.
 *
 * @internal
 * @throws Error when the model does not register the type, which means the SDL and the server
 * disagree.
 */
function objectType(
  objects: ReadonlyMap<string, GraphQLObjectType>,
  name: string,
): GraphQLObjectType {
  const type = objects.get(name);
  if (type === undefined) throw new Error("the model has no GraphQL type " + name);
  return type;
}

/**
 * The `Trail`'s `changes`: the `base..head` pairs it moved the code to, oldest first.
 *
 * @param parent - The `TrailView` the `trail` / `trails` field resolved to.
 * @param _args - No arguments.
 * @param context - The request's reads and budget.
 * @returns The Changes with their global ids.
 *
 * @throws QueryReadError with `unavailable` when the store cannot read the Change rows.
 *
 * @remarks
 * The list hangs off the Trail's own id, so a list read of many Trails reads each Trail's Changes
 * only when the selection asks for them (a field resolver runs per selected field, not per row).
 * `store.trails.listChanges` throws for a row it cannot parse (0230: it is the one throwing read
 * of that repository); an unreadable Change is `unavailable` like any other failed read, never an
 * empty list. The budget is charged one row for the Trail whose id this decodes; the Change rows
 * themselves are not charged until 0149 gives the store a bounded read.
 */
async function resolveTrailChanges(
  parent: TrailView,
  _args: Record<string, never>,
  context: GraphQLContext,
): Promise<readonly TrailChangeView[]> {
  const trailId = rawTrailId(parent);
  if (!context.budget.spend(1)) {
    throw new QueryReadError("limit_exceeded", "This request reads more rows than it may.");
  }
  let changes: readonly TrailChange[];
  try {
    changes = await context.reads.trailChanges(trailId);
  } catch (error) {
    // A corrupt Change row is a `ValiError`; it is a read that failed, not a defect of the
    // caller's request, so it is a typed failure like an outage.
    if (!(error instanceof v.ValiError)) throw error;
    console.error("graphql: trail changes could not be parsed", context.requestId);
    throw new QueryReadError("unavailable", "The stored trail changes could not be read.");
  }
  return changes.map(trailChangeView);
}

/**
 * The stored Trail id behind a Trail a Query field or a mutation payload resolved.
 *
 * @internal
 * @param view - The `TrailView` such a field returned. GraphQL passes exactly what the parent
 * field resolved, and that field's type says it is a `TrailView`.
 * @returns The id the store holds, decoded from the view's global id.
 * @throws QueryReadError with `invalid_request` for a view whose id is not a `Trail` global id.
 *
 * @remarks
 * The parent object is built by the server, so a value that does not decode is a defect. It is
 * still refused as a typed failure rather than thrown as an internal error, because the answer is
 * a 200 union member either way and the client can tell "your request chose a field the data does
 * not have" from "the server crashed".
 */
function rawTrailId(view: TrailView): string {
  const decoded = fromGlobalId(view.id);
  if (!decoded.ok || decoded.value.type !== "Trail") {
    throw new QueryReadError("invalid_request", "The parent is not a Trail.");
  }
  return decoded.value.id;
}

/**
 * The `Trail` object type: the model's fields plus the lists a Trail resolves from its own id.
 *
 * @param objects - The model object types the schema is built with.
 * @returns The object type every Query field and mutation payload uses for a Trail.
 *
 * @remarks
 * `changes` is resolved here because it is another table rather than a column. The lists
 * `trail-model-v1` §6.2 also names (`sessions`, `findings`, `decisions`, `gates`) are not on
 * this type yet: 0230's repository does not read them, so a field would have no source. They are
 * added when a resolver can answer them, not before.
 */
function trailType(objects: ReadonlyMap<string, GraphQLObjectType>): GraphQLObjectType {
  const trail = objectType(objects, "Trail");
  const change = objectType(objects, "TrailChange");
  // The parent is a `TrailView`: the only fields that resolve a Trail are the Query's `trail` /
  // `trails` and the mutation payloads, and each answers a view.
  const fields: GraphQLFieldConfigMap<TrailView, GraphQLContext> = {};
  for (const [name, field] of Object.entries(trail.getFields())) {
    // A model field has no field resolver of its own: GraphQL reads the view's property.
    if (field.resolve === undefined) fields[name] = { type: field.type };
    else fields[name] = { type: field.type, resolve: field.resolve };
  }
  fields["changes"] = {
    type: new GraphQLNonNull(new GraphQLList(new GraphQLNonNull(change))),
    resolve: resolveTrailChanges,
  };
  return new GraphQLObjectType<TrailView, GraphQLContext>({ name: "Trail", fields });
}

/**
 * The schema's single `Trail` instance for this build.
 *
 * @internal
 * @param objects - The model object types the schema is built with.
 * @param overrides - The stand-ins the schema keeps. The Query root runs first, so it creates the
 * Trail; a later root that asked would get the same instance.
 * @returns The instance, which the caller records in `overrides`.
 *
 * @remarks
 * The Query root and the mutation module's payloads must name one instance (a schema holds one
 * type per name), so the Query root records the stand-in in `overrides` and the module
 * (`./mutations/trail.ts`) reads it back.
 */
function trailOverride(
  objects: ReadonlyMap<string, GraphQLObjectType>,
  overrides: ReadonlyMap<string, GraphQLObjectType>,
): GraphQLObjectType {
  const existing = overrides.get("Trail");
  if (existing !== undefined) return existing;
  return trailType(objects);
}

/** A payload type that wraps one list field. */
function listPayload(name: string, field: string, element: GraphQLObjectType): GraphQLObjectType {
  return new GraphQLObjectType({
    name,
    fields: {
      [field]: { type: new GraphQLNonNull(new GraphQLList(new GraphQLNonNull(element))) },
    },
  });
}

/**
 * A result union: the payload or a typed failure.
 *
 * @internal
 * @remarks
 * The resolved value says which member it is by its `__typename`, so a failure can never be
 * mistaken for an empty list and no runtime class check is needed.
 */
function resultUnion(name: string, payload: GraphQLObjectType): GraphQLUnionType {
  return new GraphQLUnionType({
    name,
    types: [payload, QueryFailureType],
    resolveType: (value: { readonly __typename: string }): string => value.__typename,
  });
}

/**
 * Build the Query root over the model's own object types.
 *
 * @param objects - The model object types the schema is built with.
 * @param overrides - The stand-ins the schema keeps between its roots; this function records
 * `Trail`.
 * @returns The Query root; each field names its source in {@link resolveProjects},
 * {@link resolveTrails}, {@link resolveTrail}, or {@link resolveConversations}.
 *
 * @remarks
 * The root references the instances it is given, so the schema holds one `Project` type rather
 * than a second definition with the same name. `Trail` is the exception the overrides carry: it is
 * a copy of the model's with the lists it resolves from its id, and every other root names the
 * same copy.
 */
function buildQuery(
  objects: ReadonlyMap<string, GraphQLObjectType>,
  overrides: ReadonlyMap<string, GraphQLObjectType>,
): GraphQLObjectType {
  const projectList = listPayload("ProjectList", "projects", objectType(objects, "Project"));
  // The conversation payload carries the keyset cursor, so it is built here rather than by
  // listPayload: the list is a page, and the client needs the position to ask for the next one.
  const conversationList = new GraphQLObjectType({
    name: "ConversationList",
    fields: {
      conversations: {
        type: new GraphQLNonNull(
          new GraphQLList(new GraphQLNonNull(objectType(objects, "Conversation"))),
        ),
      },
      nextCursor: { type: GraphQLString },
    },
  });
  // The Trail's `changes` is not a stored column: it is read from the Trail's id, so the object
  // type the Query and every mutation payload name is a copy of the model's with that one field
  // added. Two types called `Trail` in one schema are refused by GraphQL, so the copy replaces
  // the model's instance rather than sitting beside it.
  // SAFETY: `buildSchema` hands every root factory a `Map` (it fills the map as roots define their
  // stand-ins); the factory signature only promises `ReadonlyMap`, and this is the map it was
  // given. The alternative — a mutable map in the contract — would let any root rewrite another's.
  const standIns: Map<string, GraphQLObjectType> = overrides as Map<string, GraphQLObjectType>;
  const trail = trailOverride(objects, overrides);
  standIns.set("Trail", trail);
  const trailList = listPayload("TrailList", "trails", trail);
  const trailPayload = new GraphQLObjectType({
    name: "TrailPayload",
    fields: { trail: { type: new GraphQLNonNull(trail) } },
  });
  const machineList = listPayload("MachineList", "machines", objectType(objects, "Machine"));
  const indexState = new GraphQLObjectType({
    name: "IndexState",
    fields: {
      pending: { type: new GraphQLNonNull(GraphQLInt) },
      lastSyncedAt: { type: GraphQLString },
      lastErrorCode: { type: GraphQLString },
      lastErrorAt: { type: GraphQLString },
    },
  });

  return new GraphQLObjectType<undefined, GraphQLContext>({
    name: "Query",
    fields: {
      projects: {
        type: new GraphQLNonNull(resultUnion("ProjectListResult", projectList)),
        args: { first: { type: GraphQLInt } },
        resolve: resolveProjects,
      },
      conversations: {
        type: new GraphQLNonNull(resultUnion("ConversationListResult", conversationList)),
        args: {
          projectId: { type: new GraphQLNonNull(GraphQLID) },
          first: { type: GraphQLInt },
          after: { type: GraphQLString },
          q: { type: GraphQLString },
        },
        resolve: resolveConversations,
      },
      indexState: {
        type: new GraphQLNonNull(resultUnion("IndexStateResult", indexState)),
        args: { projectId: { type: new GraphQLNonNull(GraphQLID) } },
        resolve: resolveIndexState,
      },
      trails: {
        type: new GraphQLNonNull(resultUnion("TrailListResult", trailList)),
        args: {
          // Optional: without it the list spans every project, which is one Sidebar.
          projectId: { type: GraphQLID },
          first: { type: GraphQLInt },
        },
        resolve: resolveTrails,
      },
      trail: {
        type: new GraphQLNonNull(resultUnion("TrailResult", trailPayload)),
        args: { id: { type: new GraphQLNonNull(GraphQLID) } },
        resolve: resolveTrail,
      },
      machines: {
        type: new GraphQLNonNull(resultUnion("MachineListResult", machineList)),
        args: { first: { type: GraphQLInt } },
        resolve: resolveMachines,
      },
      // The policy fields own their payload and failure types (`./policy/`), so this root only
      // names them; their union member is `PolicyFailure`, not the `QueryFailure` above.
      ...policyQueryFields(),
    },
  });
}

/**
 * The Mutation root builder, or undefined when no feature has registered a module.
 *
 * @internal
 * @remarks
 * The absence is what keeps the schema free of an empty Mutation root: GraphQL refuses a
 * Mutation type with no fields, and the published SDL must not change until a write exists.
 */
function mutationOf(modules: readonly MutationModule[]): MutationRootFactory | undefined {
  if (modules.length === 0) return undefined;
  return (objects, overrides) => buildMutationRoot(objects, modules, overrides);
}

/**
 * Build the schema the Worker serves.
 *
 * @param modules - The feature mutation modules to collect; production uses
 * {@link MUTATION_MODULES}. An empty collection leaves the schema without a Mutation root.
 * @returns The model types, the result unions, and the Query root (and the Mutation root when a
 * module is registered), ready for `validate` and `execute`.
 */
export function buildGraphQLSchema(
  modules: readonly MutationModule[] = MUTATION_MODULES,
): GraphQLSchema {
  return buildSchema(buildQuery, mutationOf(modules));
}

/**
 * The schema as SDL, for the client code generator.
 *
 * @param modules - The feature mutation modules to collect; production uses
 * {@link MUTATION_MODULES}.
 * @returns The printed schema, preceded by a generated header and ending in a newline.
 *
 * @remarks
 * The web package commits this as `schema.graphql`; relay-compiler validates the app's documents
 * against it. Regenerate with `npm run codegen` instead of editing it.
 */
export function buildSchemaSdl(modules: readonly MutationModule[] = MUTATION_MODULES): string {
  return SDL_HEADER + "\n" + SDL_COMMAND + "\n" + printSchema(buildGraphQLSchema(modules)) + "\n";
}
