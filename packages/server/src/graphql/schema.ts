/** The result name a Change's `diff` field declares; its payload is `ReviewDiff`. */
const REVIEW_DIFF_RESULT = "TrailChangeDiffResult";

/**
 * The `ReviewDiff` or a typed failure: what a Change's `diff` answers (C1).
 *
 * @param standIns - The schema's stand-in map, where the Query root records `ReviewDiff`.
 * @returns The union, recorded under its name so the resolver can answer either member.
 *
 * @remarks
 * The failure member is the Query's (`QueryFailure`): a diff that cannot be read is a read that
 * failed, and a client branches on the same codes as every other Trail read. A failure is a value,
 * never an empty change: an empty diff would look like "nothing changed".
 */
function reviewDiffResultType(standIns: Map<string, GraphQLNamedType>): GraphQLUnionType {
  const diff = standIns.get("ReviewDiff");
  if (!(diff instanceof GraphQLObjectType)) throw new Error("the schema has no ReviewDiff type");
  const union = new GraphQLUnionType({
    name: REVIEW_DIFF_RESULT,
    types: [diff, QueryFailureType],
    resolveType: (value: { readonly __typename: string }): string => value.__typename,
  });
  standIns.set(REVIEW_DIFF_RESULT, union);
  return union;
}

