import * as v from "valibot";
import { expect, test } from "vitest";
import {
  MACHINE_REQUEST_VERSION,
  MACHINE_RPC_PATH,
  MACHINE_WRITE_UNKNOWN_REASONS,
  SIGNED_HEADERS,
  SIGNED_HEADER_BY_FIELD,
  MachineReadResultSchema,
  MachineWriteRequestSchema,
  MachineWriteResultSchema,
  signatureMessage,
} from "./machine.ts";

const writeRequest = {
  op: "write",
  projectRoot: "projects/one",
  path: "src/a.txt",
  expectedVersion: "sha256:one",
  operationId: "op-1",
  content: "aGVsbG8=",
  contentHash: "sha256:" + "1".repeat(64),
};

// Catches: a field order, a version tag, or an encoding change on one side only,
// which would make a correctly signed request fail verification.
test("the signature message is one versioned array of the signed fields", () => {
  const message = signatureMessage({
    machineId: "m1",
    connection: "c1",
    seq: "1",
    timestamp: "0",
    nonce: "0123456789abcdef",
    method: "POST",
    path: MACHINE_RPC_PATH,
    bodyHash: "00",
  });
  expect(new TextDecoder().decode(message)).toBe(
    JSON.stringify([
      MACHINE_REQUEST_VERSION,
      "m1",
      "c1",
      "1",
      "0",
      "0123456789abcdef",
      "POST",
      "/rpc",
      "00",
    ]),
  );
  expect(MACHINE_REQUEST_VERSION).toBe("hns.machine.request.v1");
});

// Catches: a correlation header made part of the signature, which would refuse a
// request whose request id was regenerated by an intermediary.
test("x-request-id is not a signed header", () => {
  const names: readonly string[] = SIGNED_HEADERS;
  expect(names).not.toContain("x-request-id");
  expect(names).toContain("x-hns-signature");
});

// Catches: a write accepted without the intent hash, so the machine could write
// bytes the intent does not name.
test("a write request needs its project, path, intent hash, and operation id", () => {
  expect(v.parse(MachineWriteRequestSchema, writeRequest)).toStrictEqual(writeRequest);
  for (const broken of [
    { ...writeRequest, operationId: "" },
    { ...writeRequest, contentHash: "sha256:short" },
    { ...writeRequest, contentHash: "not-a-hash" },
    { ...writeRequest, expectedVersion: "" },
    { ...writeRequest, content: undefined },
    { ...writeRequest, op: "read" },
  ]) {
    expect(v.safeParse(MachineWriteRequestSchema, broken).success).toBe(false);
  }
});

// Catches: an answer rounded into a status the writer was not given.
test("a write result carries exactly one mutation status and the path", () => {
  const applied = {
    status: "applied",
    operationId: "op-1",
    version: "sha256:one",
    path: "src/a.txt",
  };
  const conflict = {
    status: "conflict",
    operationId: "op-1",
    currentVersion: "sha256:two",
    path: "src/a.txt",
  };
  const unknown = { status: "unknown", operationId: "op-1", reason: "timeout", path: "src/a.txt" };
  for (const result of [applied, conflict, unknown]) {
    expect(v.parse(MachineWriteResultSchema, result)).toStrictEqual(result);
  }
  expect(v.safeParse(MachineWriteResultSchema, { ...unknown, reason: "guess" }).success).toBe(
    false,
  );
  expect(v.safeParse(MachineWriteResultSchema, { ...applied, version: undefined }).success).toBe(
    false,
  );
  expect(MACHINE_WRITE_UNKNOWN_REASONS).toStrictEqual(["io", "crash", "timeout"]);
});

// Catches: a read answer parsed without the version that names its bytes.
test("a read result carries the bytes and their version", () => {
  const result = { path: "a.txt", size: 5, version: "sha256:one", content: "aGVsbG8=" };
  expect(v.parse(MachineReadResultSchema, result)).toStrictEqual(result);
  expect(v.safeParse(MachineReadResultSchema, { ...result, version: undefined }).success).toBe(
    false,
  );
});
// Catches: a signer and a verifier reading different header names for the same field.
// The expected names are written out, not derived from the same list, so a reordering or a
// rename of the wire contract fails here.
test("each signed field maps to its wire header", () => {
  expect(SIGNED_HEADER_BY_FIELD).toStrictEqual({
    machineId: "x-hns-machine",
    connection: "x-hns-connection",
    seq: "x-hns-seq",
    timestamp: "x-hns-timestamp",
    nonce: "x-hns-nonce",
    signature: "x-hns-signature",
  });
  expect(Object.values(SIGNED_HEADER_BY_FIELD)).toStrictEqual([...SIGNED_HEADERS]);
});
